def slots(number, role, index=None):
    """이 시안 이 판의 자리표. 없으면 None -- 부르는 쪽이 재어 쓴다.

    판마다 따로 찾는다. 판은 하나씩 생성한 것이라 안쪽 생김새가 몇 px 씩
    다르고, 역할 하나로 묶어 두면 아군 첫 줄 막대를 고쳤을 때 둘째 셋째 줄이
    같이 움직여 각자 맞출 수가 없다.

    판별 값이 없으면 역할 값으로 물러선다 -- 아직 안 가른 시안을 위해서다.
    """
    table = SLOTS.get(number, {})
    if index is not None and ("%s_%d" % (role, index)) in table:
        return table["%s_%d" % (role, index)]
    return table.get(role)
